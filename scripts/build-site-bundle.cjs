'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');

// The daily weather snapshot stays separate, and the city modules remain lazy-loaded.
const sources = ['gallery-data.js', 'script.js', 'weather-data.js', 'evidence.js', 'home-experience.js', 'site-polish.js'];
function buildSiteBundle(root = path.join(__dirname, '..')) {
  const bundle = '// Generated by scripts/build-site-bundle.cjs. Edit the source files instead.\n(() => {\n"use strict";\n' +
    sources.map(file => `\n// Source: ${file}\n${fs.readFileSync(path.join(root, file), 'utf8')}\n;`).join('\n') + '\n})();\n';
  new vm.Script(bundle, { filename:'site.js' });
  const version = crypto.createHash('sha256').update(bundle).digest('hex').slice(0, 10);
  const output = path.join(root, 'site.js');
  const changed = !fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== bundle;
  if (changed) fs.writeFileSync(output, bundle);
  const index = path.join(root, 'index.html');
  const html = fs.readFileSync(index, 'utf8');
  const updated = html.replace(/src="site\.js(?:\?v=[a-f0-9]+)?"/, `src="site.js?v=${version}"`);
  if (html === updated && !html.includes(`src="site.js?v=${version}"`)) throw new Error('Missing site.js script in index.html');
  if (updated !== html) fs.writeFileSync(index, updated);
  return { changed, version };
}
if (require.main === module) console.log(buildSiteBundle());
module.exports = { buildSiteBundle };
